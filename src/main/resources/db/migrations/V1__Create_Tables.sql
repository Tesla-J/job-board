CREATE TYPE GENDER_TYPE AS ENUM('MALE', 'FEMALE', 'OTHER');
CREATE TYPE EXPERIENCE_LEVEL_TYPE AS ENUM('INTERN', 'JUNIOR', 'MID', 'SENIOR');
CREATE TYPE CONTRACT_TYPE AS ENUM('CONTRACT', 'FULL_TIME', 'PART_TIME');
CREATE TYPE JOB_LOCATION_TYPE AS ENUM('REMOTE', 'HYBRID', 'ON_SITE');
CREATE TYPE SALARY_TYPE AS ENUM('HOUR', 'DAY', 'MONTH', 'YEAR', 'CONTRACT');

CREATE TABLE authentication (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL UNIQUE,
    password_hash CHAR(60) NOT NULL
);

CREATE TABLE candidate (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    phone_number VARCHAR(16) NOT NULL UNIQUE,
    birth_date DATE NOT NULL,
    gender GENDER_TYPE NOT NULL,
    summary VARCHAR(500) NOT NULL,
    user_id BIGINT NOT NULL UNIQUE,
    FOREIGN KEY (user_id) REFERENCES authentication(id)
);

CREATE TABLE company (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE,
    nif CHAR(10) NOT NULL UNIQUE,
    summary VARCHAR(500) NOT NULL,
    phone_number VARCHAR(16) NOT NULL UNIQUE,
    user_id BIGINT NOT NULL UNIQUE,
    FOREIGN KEY (user_id) REFERENCES authentication(id)
);

CREATE TABLE job (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(20) NOT NULL,
    description VARCHAR(500) NOT NULL,
    company_id BIGINT NOT NULL,
    experience_level EXPERIENCE_LEVEL_TYPE NOT NULL,
    contract_type CONTRACT_TYPE NOT NULL,
    job_location JOB_LOCATION_TYPE NOT NULL,
    min_salary BIGINT NOT NULL,
    max_salary BIGINT NOT NULL,
    salary_type SALARY_TYPE,
    FOREIGN KEY (company_id) REFERENCES company(id)
);

CREATE TYPE APPLICATION_STATUS_TYPE AS ENUM('SUBMITTED', 'VIEWED', 'REJECTED', 'INTERVIEWING', 'ACCEPTED');

CREATE TABLE application (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id BIGINT NOT NULL,
    candidate_id BIGINT NOT NULL,
    application_status APPLICATION_STATUS_TYPE NOT NULL,
    application_date DATE NOT NULL,
    FOREIGN KEY (job_id) REFERENCES job(id),
    FOREIGN KEY (candidate_id) REFERENCES candidate(id)
);

CREATE TABLE skill (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(20) NOT NULL UNIQUE
);

CREATE TABLE job_skill (
    job_id BIGINT NOT NULL,
    skill_id BIGINT NOT NULL,
    PRIMARY KEY (job_id, skill_id),
    FOREIGN KEY (job_id) REFERENCES job(id),
    FOREIGN KEY (skill_id) REFERENCES skill(id)
);

CREATE TABLE candidate_skill (
    candidate_id BIGINT NOT NULL,
    skill_id BIGINT NOT NULL,
    PRIMARY KEY (candidate_id, skill_id),
    FOREIGN KEY (candidate_id) REFERENCES candidate(id),
    FOREIGN KEY (skill_id) REFERENCES skill(id)
);